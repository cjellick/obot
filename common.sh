# shellcheck shell=bash
# Sourced by the kit's scripts. Never prints values from $QA_ENV_FILE.
KIT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STATE_DIR="$KIT_DIR/.state"
mkdir -p "$STATE_DIR"
chmod 700 "$STATE_DIR"

: "${QA_ENV_FILE:?set QA_ENV_FILE to the path of your credentials file (see qa.env.example)}"
if [ ! -r "$QA_ENV_FILE" ]; then
  echo "QA_ENV_FILE is not a readable file" >&2
  exit 1
fi

# Not secrets; override in your shell if needed.
: "${OBOT_IMAGE:=obot:llm-gateway}"
: "${OBOT_MODEL_DATA_URL:=https://raw.githubusercontent.com/cjellick/obot/qa-kit/model-data}"

# has_var NAME: whether $QA_ENV_FILE sets NAME to a non-empty value (prints nothing).
has_var() {
  grep -Eq "^$1=.+" "$QA_ENV_FILE"
}

# owner_email: the owner's email, which is not a secret.
owner_email() {
  sed -n 's/^OBOT_SERVER_LOCAL_AUTH_INITIAL_OWNER_EMAIL=//p' "$QA_ENV_FILE" | tail -1
}

# A one-time setup token for the initial owner, generated by the kit (not from QA_ENV_FILE)
# and kept until the install is wiped, so re-running a script prints the same link.
setup_token() {
  if [ ! -s "$STATE_DIR/setup-token-${KIT_TARGET:?}" ]; then
    (umask 077; openssl rand -hex 32 > "$STATE_DIR/setup-token-${KIT_TARGET:?}")
  fi
  cat "$STATE_DIR/setup-token-${KIT_TARGET:?}"
}

print_access() {
  local base="$1"
  echo
  echo "Obot: $base"
  if has_var OBOT_SERVER_LOCAL_AUTH_INITIAL_OWNER_EMAIL; then
    echo "Owner: $(owner_email)"
    echo "First run: set the owner's password at $base/activate#token=$(setup_token)"
    echo "  (or run ./api-login.sh $base $KIT_TARGET to set OBOT_QA_OWNER_PASSWORD and log in for the API)"
  else
    echo "No owner email in QA_ENV_FILE: log in with the bootstrap token from the server log."
  fi
}

wait_healthy() {
  local url="$1" tries="${2:-120}"
  for _ in $(seq "$tries"); do
    if [ "$(curl -s -o /dev/null -w '%{http_code}' "$url/api/healthz")" = 200 ]; then
      echo "healthy: $url/api/healthz"
      return 0
    fi
    sleep 5
  done
  echo "not healthy after $((tries * 5))s: $url/api/healthz" >&2
  return 1
}
